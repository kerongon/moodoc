#!/bin/bash

# Quick setup script for macOS code signing
# This helps you get started with the signing setup

echo "🔧 Moodle Docker Manager - macOS Signing Setup"
echo ""

# Check if Apple Developer tools are installed
if ! command -v security &> /dev/null; then
    echo "❌ macOS security tools not found. Please install Xcode Command Line Tools:"
    echo "   xcode-select --install"
    exit 1
fi

# Check for existing certificates
echo "🔍 Checking for existing code signing certificates..."
CERT_COUNT=$(security find-identity -v -p codesigning | grep -c "Developer ID Application")

if [ $CERT_COUNT -eq 0 ]; then
    echo "❌ No Developer ID Application certificates found."
    echo ""
    echo "📋 Setup Requirements:"
    echo "   1. Apple Developer account ($99/year)"
    echo "   2. Developer ID Application certificate"
    echo ""
    echo "🛠️  Setup Steps:"
    echo "   1. Sign up: https://developer.apple.com/programs/"
    echo "   2. Go to: Certificates, Identifiers & Profiles"
    echo "   3. Create: Developer ID Application certificate"
    echo "   4. Download and install in Keychain Access"
    echo "   5. Run this script again"
    echo ""
    exit 1
fi

echo "✅ Found $CERT_COUNT Developer ID Application certificate(s):"
security find-identity -v -p codesigning | grep "Developer ID Application"
echo ""

# Get the certificate name
CERT_NAME=$(security find-identity -v -p codesigning | grep "Developer ID Application" | head -1 | sed 's/.*) "//' | sed 's/".*//')
echo "🎯 Using certificate: $CERT_NAME"
echo ""

# Check if .env already exists
if [ -f ".env" ]; then
    echo "📄 .env file already exists. Backing up to .env.backup"
    cp .env .env.backup
fi

# Create .env file
echo "📝 Creating .env configuration file..."
cat > .env << EOF
# macOS Code Signing Configuration
# Generated by setup script - customize as needed

# Your Developer ID Application certificate (auto-detected)
APPLE_CERTIFICATE="$CERT_NAME"

# Apple ID for notarization (fill in your Apple ID)
APPLE_ID="your-apple-id@email.com"

# App-specific password (generate at appleid.apple.com)
# Go to: appleid.apple.com > App-Specific Passwords
APPLE_PASSWORD="your-app-specific-password"

# Your Apple Developer Team ID (find in Apple Developer Portal)
APPLE_TEAM_ID="YOUR_TEAM_ID"

# Enable notarization for distribution
ENABLE_NOTARIZATION="true"
EOF

echo "✅ .env file created!"
echo ""
echo "🔧 Next Steps:"
echo "   1. Edit .env file with your Apple ID credentials:"
echo "      - APPLE_ID: Your Apple ID email"
echo "      - APPLE_PASSWORD: Generate at appleid.apple.com"
echo "      - APPLE_TEAM_ID: Find in Apple Developer Portal"
echo ""
echo "   2. Test the setup:"
echo "      ./build_signed.sh"
echo ""
echo "   3. For distribution:"
echo "      - Enable notarization in .env"
echo "      - Build and test on another Mac"
echo ""

# Make build script executable
chmod +x build_signed.sh
echo "✅ build_signed.sh is now executable"
echo ""
echo "🎉 Setup complete! Edit .env and run ./build_signed.sh"
